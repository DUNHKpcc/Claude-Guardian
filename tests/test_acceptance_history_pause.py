def offline():
    stack = ExitStack()
    stack.enter_context(patch.object(f, '_now', return_value=TIME))
    for target in ('builtins.open', 'io.open', 'os.open', 'socket.socket', 'socket.getaddrinfo', 'subprocess.Popen', 'os.system'):
        stack.enter_context(patch(target, side_effect=AssertionError('Pure interview attempted external I/O')))
    return stack


def base(*, history='no_incident_reported', current='active'):
    values = {**COMMON, 'Q-C03': history, 'Q-C04': current}
    return f.record_facts(f.new_state('flow-device', 'flow-account', task_id='flow-task'),
        [{'question_id': q, 'value': v} for q, v in values.items()], source=SOURCE)


def history_start(route='local'):
    state = base(history='past_suspension')
    if route != 'local':
        state = f.record_fact(state, 'Q-C05', route, source=SOURCE, observed_at=TIME)
    return state


def answer(state, qid, value):
    return f.record_fact(state, qid, value, source=SOURCE, observed_at=TIME)


def question(qid):
    return {'id': qid, 'branch': 'cleanup' if qid == 'Q-D01' else 'incident',
        'stage': 'I3', 'postcontact': False, 'prompt': PROMPTS[qid],
        'clarification': False, 'allowed_outcomes': ['reported', 'unknown', 'declined', 'deferred'],
        'requires_action_authorization': False}


def snapshot(state):
    return {'state': deepcopy(state), 'next_question': f.next_question(state),
        'applicable_questions': f.applicable_questions(state), 'assessment': f.assessment(state)}


def complete_history():
    state = history_start()
    trace = [snapshot(state)]
    state = answer(f.mark_asked(state, 'Q-D01'), 'Q-D01', 'other_device_only')
    for qid, value in HISTORY.items():
        trace.append(snapshot(state))
        state = answer(f.mark_asked(state, qid), qid, value)
    trace.append(snapshot(state))
    return state, trace


def replay():
    with offline():
        state, trace = complete_history()
        result = {'narrative_scenarios_not_executed_dialogue': SCENARIOS,
            'synthetic_prior_context': COMMON, 'T31': {'trace': trace,
            'loaded': snapshot(f.loads_state(f.dumps_state(state, host_opt_in=True)))}, 'T47': {}}
        partial = f.new_state('flow-device', 'flow-account', task_id='flow-task')
        urgent = base(current='suspended')
        for name, original in (('partial', partial), ('complete', base()), ('urgent', urgent)):
            paused = f.set_context(original, paused=True)
            loaded = f.loads_state(f.dumps_state(paused, host_opt_in=True))
            resumed = f.resume_interview(loaded, resume_id='explicit-resume-' + name)
            result['T47'][name] = {'before': snapshot(original), 'paused': snapshot(paused),
                'loaded': snapshot(loaded), 'explicit_resume': snapshot(resumed)}
        return result


class HistoryPauseAcceptanceTests(unittest.TestCase):
    def setUp(self):
        stack = offline()
        self.addCleanup(stack.close)

    def assert_closed(self, state):
        self.assertEqual(f.assessment(state)['G3'], G3)
        self.assertEqual(state['context']['contact_phase'], 'PC0')
        self.assertEqual(state['persistence_consent'], PERMISSIONS)
        self.assertEqual(state['payment_intent'], 'none')

    def test_T31_complete_history_trace_keeps_current_active_and_local_plan(self):
        original = history_start()
        self.assertEqual(f.next_question(original), question('Q-D01'))
        state, trace = complete_history()
        self.assertEqual([row['next_question'] for row in trace],
            [question('Q-D01')] + [question(q) for q in HISTORY] + [None])
        for row in trace:
            current = row['state']
            self.assertEqual(current['context']['route'], 'local')
            self.assertEqual(current['context']['route_selection_basis'], 'explicit_choice')
            self.assertEqual(current['context']['incident'], 'none')
            self.assertEqual(current['facts']['Q-C03']['value'], 'past_suspension')
            self.assertEqual(current['facts']['Q-C04']['value'], 'active')
            self.assertEqual(current['facts']['Q-C03']['subject_ref'], 'flow-account')
            self.assertEqual(current['facts']['Q-C04']['subject_ref'], 'flow-account')
            self.assertEqual(current['facts']['Q-C04']['state'], 'reported')
            self.assertNotEqual(row['assessment']['G1']['status'], 'emergency_deferred')
            self.assertFalse(any(q['branch'] in ('vm', 'vps', 'payment') for q in row['applicable_questions']))
            self.assert_closed(current)
        a = f.assessment(state)
        self.assertEqual(a['G1'], {'status': 'complete', 'unresolved_fields': []})
        self.assertEqual(a['G2'], {'status': 'pass', 'conditional_plan_only': False})
        self.assertEqual(a['cleanup'], {'selected_target': 'flow-device', 'device_history': 'other_device_only',
            'trigger': 'none', 'requested_level': 'unselected', 'next_step': 'none', 'plan_only': True,
            'action_authorized': False, 'execution_status': 'not_run', 'restriction_removal_claim': False})
        self.assertNotIn('Q-D02', state['facts'])
        for qid in ('Q-C03', 'Q-C04'):
            self.assertEqual(state['facts'][qid]['source'], SOURCE)
            self.assertEqual(state['facts'][qid]['observed_at'], TIME)
        self.assertEqual(state['facts']['Q-H02']['value']['event_month'], '2025-11')
        self.assertEqual(f.loads_state(f.dumps_state(state, host_opt_in=True)), state)

    def test_T31_history_does_not_replace_any_explicit_route(self):
        for route, branch, prefix in (('local', 'local', 'Q-L'), ('vm', 'vm', 'Q-V'), ('vps', 'vps', 'Q-S')):
            state = history_start(route)
            self.assertEqual(state['context']['route'], route)
            self.assertEqual(f.assessment(state)['route_confirmation'], 'confirmed')
            self.assertEqual(f.next_question(state), question('Q-D01'))
            selected = [q for q in f.applicable_questions(state) if q['branch'] in ('local', 'vm', 'vps')]
            self.assertTrue(selected)
            self.assertTrue(all(q['branch'] == branch and q['id'].startswith(prefix) for q in selected))
            loaded = f.loads_state(f.dumps_state(state, host_opt_in=True))
            self.assertEqual(loaded, state)
            self.assert_closed(loaded)

    def test_T31_real_current_restriction_is_not_dismissed_as_history(self):
        original, _ = complete_history()
        current = f.record_fact(original, 'Q-C04', 'suspended', source='synthetic:new-current-report', observed_at=LATER)
        self.assertEqual(original['facts']['Q-C04']['value'], 'active')
        self.assertEqual(current['facts']['Q-C03'], original['facts']['Q-C03'])
        self.assertEqual(current['context']['route'], 'local')
        self.assertEqual(f.assessment(current)['G1']['status'], 'emergency_deferred')
        self.assertEqual(f.assessment(current)['G2'], {'status': 'blocked', 'conditional_plan_only': True,
            'reason': 'device_cleanup_incident_triage_required'})
        expected = question('Q-H01')
        expected.update(stage='I0', clarification=True)
        self.assertEqual(f.next_question(current), expected)
        self.assertTrue(all(q['branch'] == 'incident' for q in f.applicable_questions(current)))
        self.assert_closed(current)

    def test_T47_pause_stops_partial_complete_and_urgent_paths(self):
        for original in (f.new_state('flow-device', 'flow-account'), base(), base(current='suspended')):
            before = deepcopy(original)
            paused = f.set_context(original, paused=True)
            for _ in range(3):
                self.assertIsNone(f.next_question(paused))
                a = f.assessment(paused)
                self.assertEqual(a['G1'], {'status': 'paused', 'unresolved_fields': f.assessment(original)['G1']['unresolved_fields']})
                self.assertEqual(a['G2'], {'status': 'blocked', 'conditional_plan_only': True})
                self.assertEqual(a['G3'], G3)
                self.assertEqual(paused['facts'], before['facts'])
                self.assertEqual(paused['asked_question_ids'], before['asked_question_ids'])
                self.assertEqual(paused['context']['contact_phase'], 'PC0')
                self.assertEqual(paused['persistence_consent'], PERMISSIONS)
            self.assertEqual(original, before)

    def test_T47_loading_pause_does_not_continue_or_restore_save_permission(self):
        for original in (f.new_state('flow-device', 'flow-account'), base()):
            paused = f.set_context(original, paused=True)
            with self.assertRaisesRegex(f.InterviewError, '^Explicit host opt-in for persistence/export is required$'):
                f.dumps_state(paused)
            loaded = f.loads_state(f.dumps_state(paused, host_opt_in=True))
            self.assertEqual(loaded, paused)
            self.assertIsNone(f.next_question(loaded))
            self.assertEqual(f.assessment(loaded)['G2']['status'], 'blocked')
            self.assertEqual(f.assessment(loaded)['G3'], G3)
            with self.assertRaisesRegex(f.InterviewError, '^Use resume_interview for an interrupted session$'):
                f.set_context(loaded, paused=False)

    def test_T47_explicit_continue_still_requires_current_review_of_retained_facts(self):
        paused = f.set_context(base(), paused=True)
        resumed = f.resume_interview(paused, resume_id='resume-explicitly-requested')
        self.assertFalse(resumed['context']['paused'])
        self.assertEqual(resumed['facts'], paused['facts'])
        self.assertIsNone(f.next_question(resumed))
        self.assertEqual(resumed['resume_review']['status'], 'pending')
        self.assertEqual(f.assessment(resumed)['G2'], {'status': 'blocked', 'conditional_plan_only': True,
            'reason': 'resume_review_required'})
        self.assertEqual(f.resume_review_prompt(resumed)['kind'], 'resume_review')
        self.assert_closed(resumed)


